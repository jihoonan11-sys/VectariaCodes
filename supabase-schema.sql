create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Creator',
  handle text not null default 'creator',
  bio text not null default 'Creator profile for VectariaCodes.',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists profiles_handle_lower_idx
  on public.profiles (lower(handle));

create table if not exists public.projects (
  id text primary key default gen_random_uuid()::text,
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  category text not null check (category in ('CSS Themes','UserScripts','Game Mods')),
  description text not null,
  tags text[] not null default '{}',
  file_name text not null,
  code text not null,
  likes_count integer not null default 0 check (likes_count >= 0),
  views_count integer not null default 0 check (views_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists projects_owner_name_lower_idx
  on public.projects (owner_id, lower(name));

create index if not exists projects_created_at_idx
  on public.projects (created_at desc);

create index if not exists projects_category_idx
  on public.projects (category);

create table if not exists public.project_likes (
  project_id text not null references public.projects(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (project_id, user_id)
);

create table if not exists public.activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  project_id text references public.projects(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.projects enable row level security;
alter table public.project_likes enable row level security;
alter table public.activity enable row level security;

