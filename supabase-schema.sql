-- Secure counters behind database functions so the browser never needs an elevated key.
create or replace function public.increment_project_view(p_project_id text)
returns void
language sql
security definer
set search_path = public
as $$
  update public.projects
  set views_count = views_count + 1,
      updated_at = now()
  where id = p_project_id;
$$;

grant execute on function public.increment_project_view(text) to anon, authenticated;

create or replace function public.toggle_project_like(p_project_id text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  now_liked boolean;
begin
  if uid is null then
    raise exception 'Authentication required';
  end if;

  if exists (
    select 1 from public.project_likes
    where project_id = p_project_id and user_id = uid
  ) then
    delete from public.project_likes
    where project_id = p_project_id and user_id = uid;
    update public.projects
    set likes_count = greatest(likes_count - 1, 0), updated_at = now()
    where id = p_project_id;
    now_liked := false;
  else
    insert into public.project_likes(project_id, user_id)
    values (p_project_id, uid);
    update public.projects
    set likes_count = likes_count + 1, updated_at = now()
    where id = p_project_id;
    now_liked := true;
  end if;

  return now_liked;
end;
$$;

grant execute on function public.toggle_project_like(text) to authenticated;

